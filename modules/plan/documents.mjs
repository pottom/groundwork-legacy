// Component types, shown as a label on the map.
export const COMPONENT_TYPES = {
  software: 'szoftver',
  service: 'szolgáltatás',
  infra: 'infrastruktúra',
  shared: 'közös',
}

const kindOf = (kind) => KINDS[kind] || { file: null, label: kind, subtitle: kind, cross: CROSS_DEFAULT }

export function slug(text) {
  return String(text).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'doc'
}

// All documents in the map, in map order.
//   {id, kind, label, component: {id, topic, type} | null, file, node}
// file is relative to BASE_DIR.
export function listDocs(data) {
  const root = data.nodeData
  const docs = []
  const add = (node, component) => {
    const kind = node.metadata.doc
    const k = kindOf(kind)
    const name = node.metadata.file || k.file || `${slug(node.topic)}.md`
    docs.push({ id: node.id, kind, label: node.topic, component, file: component ? `${slug(component.dir || component.topic)}/${name}` : name, node })
  }
  for (const n of root.children || []) {
    if (n.metadata?.doc) add(n, null)
    else if (n.metadata?.component) {
      const component = { id: n.id, topic: n.topic, type: n.metadata.component, dir: n.metadata.dir }
      for (const d of n.children || []) if (d.metadata?.doc) add(d, component)
    }
  }
  if (!docs.length) docs.push({ id: root.id, kind: 'prd', label: 'PRD', component: null, file: 'PRD.md', node: root, legacy: true })
  // two documents must never share a file
  const seen = new Map()
  for (const d of docs) {
    const n = (seen.get(d.file) || 0) + 1
    seen.set(d.file, n)
    if (n > 1) d.file = d.file.replace(/\.md$/, `-${n}.md`)
  }
  return docs
}

// Which document a node belongs to (null for the root, components and stray nodes).
export function docOf(data, id) {
  const contains = (n) => n.id === id || (n.children || []).some(contains)
  for (const d of listDocs(data)) {
    if (d.legacy) return id === data.nodeData.id ? null : d.id
    if (contains(d.node)) return d.id
  }
  return null
}

// True for a node that is a section (holds prose/progress).
export function isSection(data, id) {
  return listDocs(data).some((d) => (d.node.children || []).some((s) => s.id === id))
}

export function docTitle(data, doc) {
  const root = data.nodeData.topic
  if (doc.legacy || (doc.kind === 'prd' && !doc.component && listDocs(data).filter((d) => d.kind === 'prd').length === 1)) return root
  return doc.component ? `${root} — ${doc.component.topic}: ${doc.label}` : `${root} — ${doc.label}`
}

export function buildPrd(data, docId) {
  const docs = listDocs(data)
  const doc = docs.find((d) => d.id === docId) || docs[0]
  const prd = {
    doc, kind: doc.kind, title: docTitle(data, doc), subtitle: kindOf(doc.kind).subtitle, cross: kindOf(doc.kind).cross,
    sections: [], nonGoals: [], later: [], open: [],
  }

  for (const topic of doc.node.children || []) {
    const items = []
    const visit = (node, depth) => {
      for (const c of node.children || []) {
        const st = c.metadata?.status
        const ref = { id: c.id, topic: c.topic, status: st, impl: c.metadata?.impl, note: c.note, link: c.hyperLink, section: topic.topic, depth }
        if (st === 'excluded') prd.nonGoals.push(ref)
        else if (st === 'parked') prd.later.push(ref)
        else if (st === 'todo') prd.open.push(ref)
        else items.push(ref)
        visit(c, depth + 1)
      }
    }
    visit(topic, 0)

    const m = topic.metadata || {}
    const human = m.humanProse || []
    const touched = items.length || m.prose || human.length ||
      prd.nonGoals.concat(prd.later, prd.open).some((r) => r.section === topic.topic)
    const progress = m.progress === 'done' ? 'done' : touched ? 'active' : 'untouched'
    if (progress === 'untouched') prd.open.push({ id: topic.id, topic: topic.topic, status: 'topic', section: topic.topic, untouched: true, depth: 0 })

    prd.sections.push({ id: topic.id, title: topic.topic, progress, prose: m.prose || '', human, items })
  }
  return prd
}

export function progressSummary(prd) {
  const count = { done: 0, active: 0, untouched: 0, inferred: 0, impl: { done: 0, partial: 0, missing: 0 } }
  for (const s of prd.sections) {
    count[s.progress]++
    for (const it of s.items) {
      if (it.status === 'inferred') count.inferred++
      if (it.impl) count.impl[it.impl]++
    }
  }
  return count
}

// ---------- Markdown export ----------

// Links on the map are relative to the project root; rewrite them for a file
// that lives at BASE_DIR/<file>.
function relLink(link, file) {
  if (/^[a-z]+:|^#|^\//i.test(link)) return link
  const depth = `${BASE_DIR}/${file}`.split('/').length - 1
  return '../'.repeat(depth) + link
}

function itemLine(it, file) {
  const indent = '  '.repeat(it.depth)
  const text = it.status === 'topic' ? `**${it.topic}**` : it.status === 'note' ? `_${it.topic}_` : it.topic
  const impl = it.impl ? ` \`${IMPL_LABEL[it.impl]}\`` : ''
  const inferred = it.status === 'inferred' ? ' _(kódból, megerősítésre vár)_' : ''
  const note = it.note ? ` — ${it.note}` : ''
  const link = it.link ? ` ([${it.link}](${relLink(it.link, file)}))` : ''
  return `${indent}- ${text}${impl}${inferred}${note}${link}`
}

function refLine(r, file) {
  const note = r.note ? ` — ${r.note}` : ''
  const link = r.link ? ` ([${r.link}](${relLink(r.link, file)}))` : ''
  return r.untouched ? `- **${r.topic}**: még nem beszéltük át` : `- ${r.topic}${note}${link} _(${r.section})_`
}

// siblings: the other documents, for the "see also" line.
export function toMarkdown(prd, { glossary, siblings = [] } = {}) {
  const file = prd.doc.file
  const fromHere = (other) => {
    const up = file.split('/').length - 1
    return '../'.repeat(up) + other
  }
  const see = siblings.length ? ` Kapcsolódó: ${siblings.map((s) => `[${s.component ? `${s.component.topic}: ` : ''}${s.label}](${fromHere(s.file)})`).join(', ')}.` : ''
  const out = [GENERATED_MARK, '', `# ${prd.title}`, '', `_${prd.subtitle}. A grilling-interjú közben készül; a felsorolások a gondolattérképből jönnek.${see}_`, '']
  const c = progressSummary(prd)
  const implTotal = c.impl.done + c.impl.partial + c.impl.missing
  out.push(`> Állapot: ${c.done} kész, ${c.active} folyamatban, ${c.untouched} érintetlen fejezet.` +
    (c.inferred ? ` ${c.inferred} kódból kiolvasott elem megerősítésre vár.` : '') +
    (implTotal ? ` Megvalósítás: ${c.impl.done} kész, ${c.impl.partial} részben, ${c.impl.missing} hiányzik.` : ''), '')

  prd.sections.forEach((s, i) => {
    out.push(`## ${i + 1}. ${s.title}`, '')
    if (s.prose) out.push(s.prose.trim(), '')
    for (const h of s.human) out.push(h.text.trim(), '')
    if (s.items.length) out.push(...s.items.map((it) => itemLine(it, file)), '')
    if (!s.prose && !s.human.length && !s.items.length) out.push('_Még nem beszéltük át._', '')
  })

  for (const [title, list] of [[prd.cross.nonGoals, prd.nonGoals], [prd.cross.later, prd.later], [prd.cross.open, prd.open]]) {
    if (!list.length) continue
    out.push(`## ${title}`, '', ...list.map((r) => refLine(r, file)), '')
  }
  if (glossary && (prd.kind === 'prd' || prd.kind === 'system')) out.push('## Fogalmak', '', `Lásd: [GLOSSARY.md](${relLink('GLOSSARY.md', file)})`, '')
  return out.join('\n')
}
